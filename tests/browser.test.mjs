import assert from 'node:assert/strict';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, timezoneId: 'America/Los_Angeles' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  assert.equal(await page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().width), 320);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.ok(await page.getByLabel('Daily note', { exact: true }).evaluate(el => el.getBoundingClientRect().height) > 160);
  await page.getByRole('button', { name: 'Add item', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Add item' });
  await dialog.getByLabel('Title').focus();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await dialog.evaluate(el => el.contains(document.activeElement)), true);
  for (let index = 0; index < 8; index++) {
    await page.keyboard.press('Tab');
    assert.equal(await dialog.evaluate(el => el.contains(document.activeElement)), true);
  }
  await dialog.getByLabel('Title').fill('Browser task');
  await dialog.getByLabel('Date', { exact: true }).fill('2024-02-29');
  await dialog.getByRole('button', { name: '[Add]', exact: true }).click();
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  await page.getByRole('button', { name: 'Add item', exact: true }).focus();
  await page.keyboard.press('Enter');
  assert.equal(await dialog.isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Add item', exact: true }).evaluate(el => el === document.activeElement), true);
  await page.getByRole('button', { name: 'Add item', exact: true }).click();
  await dialog.getByLabel('Title').fill('Browser habit');
  await dialog.getByLabel('Type', { exact: true }).selectOption('habit');
  assert.equal(await dialog.getByLabel('Date', { exact: true }).count(), 0);
  await dialog.getByRole('button', { name: '[Add]', exact: true }).click();
  const habit = page.getByRole('checkbox', { name: 'Browser habit', exact: true });
  await habit.check();
  assert.equal(await habit.isChecked(), true);
  const todayCell = page.locator('button[aria-current="date"]');
  assert.match(await todayCell.getAttribute('aria-label'), /1 habits completed/);
  await habit.uncheck();
  assert.match(await todayCell.getAttribute('aria-label'), /0 habits completed/);
  await habit.check();
  await todayCell.focus();
  await page.keyboard.press('Enter');
  const panel = page.getByRole('complementary', { name: 'Day details' });
  assert.equal(await panel.evaluate(el => el.contains(document.activeElement)), true);
  await page.keyboard.press('Escape');
  assert.equal(await panel.count(), 0);
  assert.equal(await todayCell.evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Enter');
  assert.equal(await panel.getByText('Browser habit', { exact: true }).count(), 1);
  await panel.getByRole('button', { name: 'Edit Browser habit', exact: true }).click();
  await panel.getByLabel('Title', { exact: true }).fill('Renamed habit');
  await panel.getByRole('button', { name: '[Save]', exact: true }).click();
  assert.equal(await page.getByRole('checkbox', { name: 'Renamed habit' }).isChecked(), true);
  await panel.getByRole('button', { name: 'Delete Renamed habit', exact: true }).click();
  assert.equal(await page.getByRole('checkbox', { name: 'Renamed habit' }).count(), 0);
  await page.getByLabel('Daily note', { exact: true }).fill('Today note');
  assert.equal(await panel.getByText('Today note', { exact: true }).count(), 1);
  await page.getByLabel('Note date', { exact: true }).fill('2024-02-29');
  await page.getByLabel('Daily note', { exact: true }).fill('Leap day note');
  await page.getByRole('button', { name: '[All notes]', exact: true }).click();
  const notes = page.getByRole('dialog', { name: 'All notes' });
  await notes.getByRole('button', { name: /2024-02-29 Leap day note/ }).click();
  assert.equal(await page.getByLabel('Daily note', { exact: true }).inputValue(), 'Leap day note');
  await panel.getByRole('button', { name: '[Close]', exact: true }).click();
  await page.getByRole('button', { name: 'Week', exact: true }).click();
  assert.equal(await page.locator('.day-cell').count(), 7);
  await page.getByRole('button', { name: 'Month', exact: true }).click();
  await page.reload();
  assert.equal(await page.getByRole('checkbox', { name: 'Renamed habit' }).count(), 0);
  await page.getByLabel('Note date', { exact: true }).fill('2024-02-29');
  assert.equal(await page.getByLabel('Daily note', { exact: true }).inputValue(), 'Leap day note');
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  await page.locator('button[aria-current="date"]').click();
  await panel.getByRole('button', { name: 'Add item for selected day' }).click();
  await dialog.getByLabel('Title').fill('Detail task');
  await dialog.getByRole('button', { name: '[Add]', exact: true }).click();
  await panel.getByRole('button', { name: 'Edit Detail task' }).click();
  await panel.getByLabel('Title', { exact: true }).fill('Changed task');
  await panel.getByRole('button', { name: '[Save]', exact: true }).click();
  await panel.getByRole('button', { name: 'Delete Changed task' }).click();
  assert.equal(await page.getByRole('checkbox', { name: 'Changed task' }).count(), 0);
  await panel.getByRole('button', { name: '[Close]', exact: true }).click();
  await page.getByRole('button', { name: '[All notes]', exact: true }).click();
  await page.mouse.click(5, 5);
  assert.equal(await page.getByRole('dialog').count(), 0);
  const remainingTask = page.getByRole('checkbox', { name: 'Browser task', exact: true });
  await page.evaluate(() => {
    window.originalSetItem = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) {
      if (key === 'text-companion-todo-items') throw new DOMException('Quota reached', 'QuotaExceededError');
      return window.originalSetItem.call(this, key, value);
    };
  });
  await remainingTask.click();
  assert.equal(await remainingTask.isChecked(), false);
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await page.getByRole('button', { name: '[Retry save]', exact: true }).click();
  assert.equal(await remainingTask.isChecked(), true);
  await page.getByRole('button', { name: 'Add item', exact: true }).click();
  await dialog.getByLabel('Title').fill('Pending habit');
  await dialog.getByLabel('Type', { exact: true }).selectOption('habit');
  await dialog.getByRole('button', { name: '[Add]', exact: true }).click();
  const pendingHabit = page.getByRole('checkbox', { name: 'Pending habit', exact: true });
  await page.evaluate(() => {
    window.originalSetItem = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) {
      if (key === 'text-companion-daily-tasks') throw new DOMException('Quota reached', 'QuotaExceededError');
      return window.originalSetItem.call(this, key, value);
    };
  });
  await pendingHabit.click();
  await remainingTask.click();
  assert.equal(await page.getByRole('alert').isVisible(), true);
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await page.getByRole('button', { name: '[Retry save]', exact: true }).click();
  assert.equal(await pendingHabit.isChecked(), true);
  assert.equal(await remainingTask.isChecked(), false);
  await page.evaluate(() => {
    window.originalSetItem = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) {
      if (key === 'text-companion-daily-notes') throw new DOMException('Quota reached', 'QuotaExceededError');
      return window.originalSetItem.call(this, key, value);
    };
  });
  await page.getByLabel('Daily note', { exact: true }).fill('Unsaved note must survive');
  assert.match(await page.getByRole('alert').textContent(), /Changes not saved/);
  await remainingTask.click();
  assert.match(await page.getByRole('alert').textContent(), /Changes not saved/);
  assert.equal(await page.getByRole('button', { name: '[Retry save]', exact: true }).isVisible(), true);
  const oldDate = await page.getByLabel('Note date', { exact: true }).inputValue();
  await page.getByRole('button', { name: 'Next note day' }).click();
  assert.equal(await page.getByLabel('Note date', { exact: true }).inputValue(), oldDate);
  assert.equal(await page.getByLabel('Daily note', { exact: true }).inputValue(), 'Unsaved note must survive');
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await page.getByRole('button', { name: '[Retry save]', exact: true }).click();
  assert.equal(await page.getByRole('alert').count(), 0);
  await page.reload();
  await page.getByLabel('Note date', { exact: true }).fill(oldDate);
  assert.equal(await page.getByLabel('Daily note', { exact: true }).inputValue(), 'Unsaved note must survive');
  assert.deepEqual(errors, []);
  if (process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH, fullPage: true });
  console.log('Browser: keyboard/dialog focus, habit undo, edit/delete, daily notes, reload, month/week passed.');
} finally {
  await browser.close();
}
